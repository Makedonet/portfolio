/** Кадры «живых окон» — id из live.json (их снимает скрипт съёмки). */
export type Screens = {
  /** Страницы сайта в окне браузера — по очереди, как переход по ссылкам. */
  desktop: string[];
  /** Мобильная версия в телефоне. */
  mobile?: string;
};

/** Как показать цифру: кольцо — оценка из максимума, полосы — было и стало. */
export type Visual = { type: "ring"; value: number; max: number } | { type: "bars"; before: number; after: number; unit: string };

export type Metric = { value: string; label: string; visual?: Visual };

export type Work = {
  id: string;
  title: string;
  /** Отрасль заказчика — для индекса работ под первым экраном. */
  industry: string;
  /** Что это за сайт — одной строкой под названием. */
  kind: string;
  /** Плашка состояния. `live` — сайт работает у заказчика. */
  status: { tone: "live" | "concept"; label: string };
  /** Что происходит с проектом сейчас, если есть что сказать. */
  now?: string;
  /** Задача: что нужно было бизнесу. */
  task: string;
  /** Главный результат для бизнеса — тёмной карточкой, крупными цифрами. */
  result?: { figures: Metric[]; text: string };
  /** Главное о работе одной строкой — для индекса работ. */
  highlight: string;
  /** Что сделано. */
  done: string[];
  /** Цифры с подписями; у части — наглядная картинка (Visual). */
  metrics: Metric[];
  stack: string[];
  url: string;
  urlLabel: string;
  screens: Screens;
};

