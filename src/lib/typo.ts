// Русская типографика для текстов из data/: короткие предлоги, союзы и «я»
// привязываются неразрывным пробелом к следующему слову, число — к своей
// единице («10 минут», «100 МБ»), тире — к слову перед ним, чтобы не начинать
// строку, а «Яндекс» — к названию сервиса. Слова через дефис
// («Санкт-Петербург», «152-ФЗ») не разрываются в конце строки. Неразрывного
// дефиса (U+2011) нет ни в Onest, ни в JetBrains Mono — он рисовался бы
// системным шрифтом, поэтому такие слова заворачиваются в nowrap.
// Возвращает HTML для set:html; тексты свои, но экранируются всё равно.

const SHORT = /(^|[\s(«])(а|в|во|и|к|ко|о|об|с|со|у|я|на|но|не|ни|до|по|от|за|из|без|для|под|над|при|про|что|как)\s+/gi;

const escape = (text: string) => text.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");

export function typo(text: string): string {
  // Дважды: у «и в» второй предлог иначе останется без привязки.
  const glued = text
    .replace(SHORT, "$1$2 ")
    .replace(SHORT, "$1$2 ")
    .replace(/(\d)\s+(?=\p{L})/gu, "$1 ")
    .replace(/\s+—/g, " —")
    // «Яндекс Директ», «Яндекс Метрика»: название сервиса не разрываем.
    .replace(/Яндекс\s+/g, "Яндекс ");
  return escape(glued).replace(/([^\s ]+-[^\s ]+)/g, '<span class="whitespace-nowrap">$1</span>');
}
